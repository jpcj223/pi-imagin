import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createJiti } from 'jiti';
const jiti=createJiti(import.meta.url);
const {getGitStatus,getGitFileDiff}=await jiti.import('./git-changes.ts');
const {mergeProjectGitStatuses}=await jiti.import('./file-paths.ts');
const git=(cwd,...args)=>execFileSync('git',['-C',cwd,...args],{stdio:'pipe'});
function repo(dir){ fs.mkdirSync(dir,{recursive:true});git(dir,'init');git(dir,'-c','user.name=Test','-c','user.email=test@example.invalid','commit','--allow-empty','-m','fixture'); }
test('跨仓库文件及已删除父目录的差异由目标文件确定；同仓库去重保留嵌套独立仓库',async t=>{
  const root=fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'pi-git-repairs-')));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const a=path.join(root,'a'),b=path.join(root,'b'),inner=path.join(a,'nested');repo(a);repo(b);repo(inner);
  fs.writeFileSync(path.join(a,'.gitignore'),'nested/\n');fs.mkdirSync(path.join(a,'src'));
  fs.writeFileSync(path.join(a,'src/a.txt'),'old\n');git(a,'add','.');git(a,'-c','user.name=Test','-c','user.email=test@example.invalid','commit','-m','base');
  fs.mkdirSync(path.join(b,'gone'));const deleted=path.join(b,'gone/deleted.txt'),file=path.join(b,'b.txt');
  fs.writeFileSync(deleted,'deleted\n');fs.writeFileSync(file,'old\n');git(b,'add','.');git(b,'-c','user.name=Test','-c','user.email=test@example.invalid','commit','-m','base');
  fs.writeFileSync(file,'new\n');fs.rmSync(deleted);fs.rmdirSync(path.dirname(deleted));
  assert.equal((await getGitFileDiff(a,file)).supported,true);assert.match((await getGitFileDiff(a,file)).patch,/\+new/);
  assert.equal((await getGitFileDiff(a,deleted)).status,'deleted');
  fs.writeFileSync(path.join(a,'src/a.txt'),'changed\n');fs.writeFileSync(path.join(inner,'inner.txt'),'inner\n');
  const dirs=[a,path.join(a,'src'),inner,b];
  const statuses=await Promise.all(dirs.map(async cwd=>({cwd,status:await getGitStatus(cwd)})));
  const merged=mergeProjectGitStatuses(statuses);
  assert.equal(merged.files.length,4);assert.ok(merged.files.some(f=>f.filePath===path.join(inner,'inner.txt')));
  assert.equal(merged.additions,statuses[0].status.additions+statuses[2].status.additions+statuses[3].status.additions);
  assert.equal(merged.deletions,statuses[0].status.deletions+statuses[2].status.deletions+statuses[3].status.deletions);
});
