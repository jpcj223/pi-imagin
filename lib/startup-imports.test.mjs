import assert from "node:assert/strict";
import { registerHooks } from "node:module";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import test from "node:test";
import { createJiti } from "jiti";

test("首次只读目录、列表和运行状态无需加载 SDK，且实时读取同一注册表", async t => {
  const root = mkdtempSync(join(tmpdir(), "pi-imagin-light-startup-"));
  const previous = process.env.PI_CODING_AGENT_DIR;
  const registry = globalThis.__piSessions;
  const hook = registerHooks({ resolve(specifier, context, next) {
    assert.ok(!specifier.startsWith("@earendil-works/pi-coding-agent") && !specifier.includes("pi-coding-agent/dist/"), `只读路径意外导入 SDK: ${specifier}`);
    return next(specifier, context);
  } });
  t.after(() => { hook.deregister(); globalThis.__piSessions=registry; if(previous===undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR=previous; rmSync(root,{recursive:true,force:true}); });
  process.env.PI_CODING_AGENT_DIR = root;
  const directory = join(root,"sessions","project"); mkdirSync(directory,{recursive:true});
  const timestamp="2026-01-01T00:00:00.000Z";
  const file=join(directory,"fixture.jsonl");
  writeFileSync(file,JSON.stringify({ type:"session",version:3,id:"fixture",timestamp,cwd:root })+"\n");
  const jiti=createJiti(import.meta.url);
  const reader=await jiti.import("./session-reader.ts");
  const state=await jiti.import("./session-ui-state.ts");
  const runtime=await jiti.import("./rpc-session-read.ts");
  globalThis.__piSessions=undefined;
  assert.deepEqual(runtime.getRunningRpcSessionIds(),[]);
  assert.deepEqual(runtime.getRpcSessionInfos(),[]);
  assert.equal(globalThis.__piSessions,undefined,"读取不能初始化运行时");
  assert.equal(state.readSessionUiState().version,1);
  const summaries=await reader.listSessionSummaries();
  assert.equal(summaries[0].id,"fixture");
  assert.equal(summaries[0].detailsPending,true);
  const wrapper={ sessionId:"canonical",sessionFile:file,cwd:root,isAlive:()=>true,isRunning:()=>true,isAwaitingInput:()=>true,hasSuppressedCompletionNotifications:()=>true,inner:{sessionManager:{getHeader:()=>({id:"canonical",cwd:root,timestamp}),getEntries:()=>[],getSessionFile:()=>file,getSessionName:()=>"正在运行"}} };
  globalThis.__piSessions=new Map([["alias",wrapper]]);
  assert.equal(runtime.getRpcSession("alias"),wrapper);
  assert.deepEqual(runtime.getRunningRpcSessionIds(),["canonical"]);
  assert.deepEqual(runtime.getAwaitingInputRpcSessionIds(),["canonical"]);
  assert.deepEqual(runtime.getCompletionNotificationSuppressedRpcSessionIds(),["canonical"]);
  assert.equal(runtime.getRpcSessionInfos()[0].name,"正在运行");
  wrapper.sessionFile=""; wrapper.inner.sessionManager.getSessionFile=()=>"";
  assert.deepEqual(runtime.getRpcSessionInfos(),[],"空且未持久化的运行时不能漏到历史列表");
  assert.equal(runtime.getRpcSessionInfos({includeTransient:true})[0].transient,true);
  globalThis.__piSessions.clear();
  assert.deepEqual(runtime.getRunningRpcSessionIds(),[],"不能缓存过时的运行状态");
});
