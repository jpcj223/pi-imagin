import assert from "node:assert/strict";
import test from "node:test";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { createJiti } from "jiti";
const jiti = createJiti(import.meta.url, { tsconfigPaths: true });
const { changeManagedProject, bindProjectSession, resolveCurrentProjectScope, resolveProjectToolPath, inheritProjectSession, readManagedProjects } = await jiti.import("./managed-projects.ts");
const { createProjectWorkspaceExtension } = await jiti.import("./project-workspace-extension.ts");
const { loadSubagentInputFiles } = await jiti.import("./subagent-input.ts");
const { subagentToolOptions } = await jiti.import("./subagents.ts");

test("旧会话及分支实时获取新增、改名、重排和解除关联；启动位置不漂移", async t => {
  const root = mkdtempSync(join(tmpdir(), "pi-project-live-"));
  t.after(() => rmSync(root, {recursive:true,force:true}));
  const folders = ["front","back","docs"].map(name => { const path=join(root,name);mkdirSync(path);return {name,path}; });
  const file=join(root,"projects.json");
  let p=(await changeManagedProject({action:"save",name:"动态项目",folders:folders.slice(0,2)},file)).projects[0];
  const binding=await bindProjectSession("old-session",folders[0].path,p.id,file);
  const current=()=>resolveCurrentProjectScope(binding,file);
  const hooks=new Map();
  createProjectWorkspaceExtension(binding,()=>["read","write","bash"],undefined,current).factory({on:(name,fn)=>hooks.set(name,fn),registerTool:()=>{}});
  hooks.get("before_agent_start")({systemPrompt:"原文"});
  await inheritProjectSession("old-session","fork",file);
  const initialFolder=p.defaultFolderId;
  p=(await changeManagedProject({action:"save",id:p.id,revision:p.revision,name:p.name,folders:[{...folders[2],name:"说明"},folders[1],folders[0]]},file)).projects[0];
  assert.equal(p.defaultFolderId,initialFolder);
  assert.equal(current().cwd,binding.cwd);
  assert.equal(current().folders.length,3);
  assert.equal(hooks.get("tool_call")({toolName:"write",input:{path:join(folders[2].path,"new.txt")}},{}),undefined);
  hooks.get("tool_call")({toolName:"write",toolCallId:"structured",input:{path:join(folders[2].path,"structured.txt")}},{});
  const structured={created:true};
  const result=hooks.get("tool_result")({toolName:"write",toolCallId:"structured",content:[{type:"text",text:"saved"}],structuredContent:structured,isError:false});
  assert.equal(result.structuredContent,structured);
  assert.equal(result.details.path,join(folders[2].path,"structured.txt"));
  const messages=[];
  const projected=hooks.get("context")({messages});
  assert.equal(messages.length,0);
  assert.ok(projected.messages.at(-1).content[0].text.includes("说明"));
  const child=resolveCurrentProjectScope(readManagedProjects(file).sessions.fork,file);
  assert.equal(child.folders.length,3);
  writeFileSync(join(folders[2].path,"input.txt"),"跨目录输入");
  assert.equal(loadSubagentInputFiles(binding.cwd,[join(folders[2].path,"input.txt")],current())[0].path.replaceAll("\\","/"),join(folders[2].path,"input.txt").replaceAll("\\","/"));
  p=(await changeManagedProject({action:"save",id:p.id,revision:p.revision,name:p.name,folders:[folders[0]]},file)).projects[0];
  assert.equal(current().folders.length,1);
  assert.equal(hooks.get("tool_call")({toolName:"write",input:{path:join(folders[2].path,"stale.txt")}},{}).block,true);
  assert.equal(hooks.get("tool_call")({toolName:"write",input:{path:"stale.txt"}},{}).block,true);
  assert.equal(hooks.get("tool_call")({toolName:"bash",input:{command:"echo wrong"}},{}).block,true);
  rmSync(folders[1].path,{recursive:true});
  assert.equal(resolveProjectToolPath(current(),join(folders[0].path,"valid.txt")),join(folders[0].path,"valid.txt"));
  p=(await changeManagedProject({action:"save",id:p.id,revision:p.revision,name:p.name,folders:[]},file)).projects[0];
  assert.ok(existsSync(p.workspace.path));
  assert.equal(current().folders[0].path,p.workspace.path);
  assert.equal(current().cwd,binding.cwd);
});

test("项目元数据损坏时文件守卫拒绝，不能因错误提示再次读取失败而放行", async t => {
  const root=mkdtempSync(join(tmpdir(),"pi-live-fail-closed-"));t.after(()=>rmSync(root,{recursive:true,force:true}));
  const binding={projectId:"p",projectName:"项目",cwd:root,folders:[{id:"a",name:"a",path:root}]};
  let damaged=false;const hooks=new Map();
  createProjectWorkspaceExtension(binding,undefined,undefined,()=>{if(damaged)throw new Error("损坏的项目数据");return binding;}).factory({on:(name,fn)=>hooks.set(name,fn),registerTool:()=>{}});
  damaged=true;
  assert.equal(hooks.get("tool_call")({toolName:"write",input:{path:join(root,"blocked.txt")}},{}).block,true);
});

test("子代理项目命令和复制能力只随原有工具权限开启", () => {
  assert.ok(!subagentToolOptions({tools:["read"],projectWorkspace:true}).tools.includes("project_command"));
  const full=subagentToolOptions({tools:["read","write","bash"],projectWorkspace:true});
  assert.ok(full.tools.includes("project_command"));assert.ok(full.tools.includes("project_copy_file"));
});
