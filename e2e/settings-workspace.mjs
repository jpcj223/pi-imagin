import assert from "node:assert/strict";
import { checkThemeTransitions } from "./theme-transition.mjs";
import { checkGeneralSettingsReset } from "./general-settings-reset.mjs";

// 设置与插件共用外层范围，内部配置仍保留原有草稿和滚动。
export async function checkSettingsWorkspace(page, { capture = async () => {} } = {}) {
  const viewport = page.viewportSize();
  const rail = page.locator(".workspace-rail");
  const settings = page.locator(".settings-workspace-page:not(.plugins-workspace-page)");
  const preferredWidth = await page.locator("#session-sidebar").evaluate(node => parseFloat(getComputedStyle(node).getPropertyValue("--sidebar-width")));
  await page.locator(".workspace-rail-settings").click();
  await settings.waitFor();
  await settings.getByRole("button", { name: "General", exact: true }).click();
  const general = settings.locator(".settings-general");
  const bounds = await settings.evaluate(node => ({ left: node.getBoundingClientRect().left, width: node.getBoundingClientRect().width, right: innerWidth, header: node.querySelector(".settings-dialog-header").getBoundingClientRect().height }));
  assert.equal(bounds.left, 40); assert.equal(bounds.width, bounds.right - 40); assert.equal(bounds.header, 36);
  assert.equal((await settings.locator('.settings-section-tabs').boundingBox()).width, preferredWidth, "设置沿用主页侧栏尺寸");
  const resize = async (surface, sidebar, delta) => {
    const handle = surface.getByTestId("settings-sidebar-resizer"), box = await handle.boundingBox();
    assert.ok(box);
    const before = (await sidebar.boundingBox()).width;
    await page.mouse.move(box.x + box.width / 2, box.y + 50);
    await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + delta, box.y + 50, { steps: 5 });
    assert.ok(Math.abs((await sidebar.boundingBox()).width - before - delta) <= 1, "释放前侧栏已跟随指针");
    await page.mouse.up();
    assert.equal(await page.evaluate(() => document.body.style.cursor), "");
    assert.equal(Number(await page.evaluate(() => localStorage.getItem("pi-sidebar-width"))), Math.round(before + delta));
  };
  await resize(settings, settings.locator(".settings-section-tabs"), 48);
  await resize(settings, settings.locator(".settings-section-tabs"), -48);
  assert.notEqual(await page.locator("#session-sidebar").getAttribute("inert"), null);
  assert.equal(await settings.locator(".workspace-back,.settings-dialog-close").count(), 0);
  const typography = await general.locator(".settings-chat-options").first().boundingBox();
  assert.ok(typography.width > 420 && typography.width <= 901, `内容宽度 ${typography.width}，允许缩放后的亚像素舍入`);
  const uiWeight = general.getByRole("combobox", { name: "Interface font weight", exact: true });
  await uiWeight.selectOption("500");
  assert.equal(await page.evaluate(() => getComputedStyle(document.body).fontWeight), "500");
  await general.getByRole("button", { name: "Reset interface font", exact: true }).click();
  assert.equal(await uiWeight.inputValue(), "400");
  const pushDetails = general.locator(".settings-push-details");
  assert.equal(await pushDetails.getByRole("button", { name: "Register push", exact: true }).isVisible(), false);
  await pushDetails.locator("summary").focus(); await page.keyboard.press("Enter");
  assert.equal(await pushDetails.getByRole("button", { name: "Register push", exact: true }).isVisible(), true, "收起说明不影响推送注册入口");
  await pushDetails.locator("summary").focus(); await page.keyboard.press("Enter");
  await general.evaluate(node => node.scrollTop = 0);
  await capture(page, "settings-general-wide");
  await checkThemeTransitions(page, { capture });
  await general.evaluate(node => node.scrollTop = 400);
  const scroll = await general.evaluate(node => node.scrollTop);
  await settings.getByRole("button", { name: "Models", exact: true }).click();
  await settings.locator(".models-sidebar-indented-item:not(.models-sidebar-add-item)").first().click();
  const name = settings.getByPlaceholder("Display name", { exact: true });
  await name.fill("Layout draft stays"); await capture(page, "settings-models-wide");
  await settings.getByRole("button", { name: "MCP", exact: true }).click();
  await settings.locator('[data-settings-section="mcp"]').waitFor(); await capture(page, "settings-mcp-wide");
  await settings.getByRole("button", { name: "General", exact: true }).click();
  assert.ok(Math.abs((await general.evaluate(node => node.scrollTop)) - scroll) <= 2);
  await rail.locator(".workspace-rail-plugins").click();
  const plugins = page.locator(".plugins-workspace-page"); await plugins.waitFor();
  assert.equal((await plugins.boundingBox()).x, bounds.left);
  assert.equal((await plugins.locator('.plugins-manager .config-sidebar').boundingBox()).width, preferredWidth, "插件沿用主页侧栏尺寸");
  await resize(plugins, plugins.locator('.plugins-manager .config-sidebar'), 36);
  const pluginHandle = plugins.getByTestId("settings-sidebar-resizer");
  await pluginHandle.press("ArrowLeft");
  assert.equal((await plugins.locator('.plugins-manager .config-sidebar').boundingBox()).width, preferredWidth + 24);
  await resize(plugins, plugins.locator('.plugins-manager .config-sidebar'), -24);
  await pluginHandle.dblclick();
  assert.equal((await plugins.locator('.plugins-manager .config-sidebar').boundingBox()).width, 220);
  if (preferredWidth !== 220) await resize(plugins, plugins.locator('.plugins-manager .config-sidebar'), preferredWidth - 220);
  await page.locator(".workspace-rail-settings").click();
  await settings.getByRole("button", { name: "Models", exact: true }).click();assert.equal(await name.inputValue(), "Layout draft stays");
  await settings.getByRole("button", { name: "General", exact: true }).click();
  await general.evaluate(node => node.scrollTop = 0);
  await settings.locator(".settings-language-option").filter({hasText:"简体中文"}).click();
  await capture(page, "settings-language-row");
  await general.evaluate(node => node.scrollTop = 0);
  await capture(page, "settings-general-chinese");
  await settings.locator(".settings-theme-option").filter({ hasText: /^深色$/ }).click(); await capture(page, "settings-general-dark");
  await page.setViewportSize({ width: 900, height: 800 });
  assert.equal((await settings.boundingBox()).x, 40); await capture(page, "settings-medium");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('.settings-workspace-page:not([hidden])')?.getBoundingClientRect().left === 0);
  assert.ok(await settings.getByRole("button", { name: "主页", exact: true }).isVisible());
  assert.equal(await settings.getByTestId("settings-sidebar-resizer").isVisible(), false);
  assert.equal(await page.locator("#session-sidebar").evaluate(node => getComputedStyle(node).visibility), "hidden");
  assert.equal(await page.locator(".sidebar-overlay-backdrop").evaluate(node => getComputedStyle(node).pointerEvents), "none");
  const size = await settings.evaluate(node => ({ width: node.clientWidth, scroll: node.scrollWidth })); assert.ok(size.scroll <= size.width + 1);
  await settings.getByRole("button", { name: "模型", exact: true }).click();
  assert.ok(await settings.locator('[data-settings-section="models"] input').evaluateAll(nodes => nodes.some(node => node.value === "Layout draft stays")));
  await capture(page, "settings-models-mobile");
  await settings.getByRole("button", { name: "常规", exact: true }).click();
  assert.equal(await general.evaluate(node => node.scrollWidth <= node.clientWidth + 1), true, "窄屏设置内容不能横向溢出");
  await general.evaluate(node => node.scrollTop = 0);
  await capture(page, "settings-general-mobile");
  await general.locator(".settings-language-options").scrollIntoViewIfNeeded();
  await capture(page, "settings-language-mobile");
  await settings.getByRole("button", { name: "主页", exact: true }).click();
  await settings.waitFor({ state: "hidden" }); assert.equal(await page.locator("#session-sidebar").getAttribute("inert"), null);
  await page.setViewportSize(viewport ?? { width: 1440, height: 1000 });
  await page.locator(".workspace-rail-settings").click();
  await settings.locator(".settings-theme-option").filter({ hasText: /^浅色$/ }).click();
  await settings.locator(".settings-language-option").filter({hasText:"English"}).click();
  await checkGeneralSettingsReset(page, { capture });
  await page.locator('.workspace-rail [data-rail-item="home"]').click();
  console.log("PASS: 设置全工作区、紧凑标题、侧栏停用、内容自适应、分区滚动与模型草稿、插件切换、中文主题和窄屏主页出口");
}
